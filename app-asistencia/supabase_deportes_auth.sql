-- Crear tabla de PINs por deporte (Profe y Coordinador) para blindar el acceso
CREATE TABLE IF NOT EXISTS public.deportes_auth (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  deporte TEXT NOT NULL UNIQUE,
  pin TEXT NOT NULL,
  pin_coord TEXT,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- Si la tabla ya existía sin la columna pin_coord, la agregamos:
ALTER TABLE public.deportes_auth ADD COLUMN IF NOT EXISTS pin_coord TEXT;

-- Habilitar lectura pública (anon) para que la app pueda validar el PIN
ALTER TABLE public.deportes_auth ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Lectura publica de deportes_auth" ON public.deportes_auth;
CREATE POLICY "Lectura publica de deportes_auth"
  ON public.deportes_auth
  FOR SELECT
  USING (true);

